create or replace view public.fcd_account_currency_balance_projection as
select
  ledger.account_id,
  ledger.currency_code,
  sum(ledger.native_amount_in - ledger.native_amount_out)::numeric(18,2) as native_balance,
  sum(ledger.carrying_thb_in - ledger.carrying_thb_out)::numeric(18,2) as carrying_thb_balance,
  case
    when sum(ledger.native_amount_in - ledger.native_amount_out) = 0 then null
    else round(
      sum(ledger.carrying_thb_in - ledger.carrying_thb_out)
      / sum(ledger.native_amount_in - ledger.native_amount_out),
      3
    )
  end as weighted_carrying_rate,
  max(ledger.entry_date) as last_entry_date
from public.fcd_ledger_entries ledger
group by ledger.account_id, ledger.currency_code;

