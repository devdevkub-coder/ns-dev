create or replace function public.validate_fcd_ledger_entry_account_currency()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if not exists (
    select 1
    from public.accounts account
    join public.account_currency_balances currency_balance
      on currency_balance.account_id = account.id
     and currency_balance.currency_code = new.currency_code
     and currency_balance.active = true
    where account.id = new.account_id
      and account.is_fcd = true
      and account.active = true
  ) then
    raise exception 'FCD ledger account % does not support active currency %', new.account_id, new.currency_code;
  end if;

  return new;
end;
$$;

drop trigger if exists validate_fcd_ledger_entry_account_currency on public.fcd_ledger_entries;
create trigger validate_fcd_ledger_entry_account_currency
before insert or update of account_id, currency_code on public.fcd_ledger_entries
for each row execute function public.validate_fcd_ledger_entry_account_currency();

create or replace function public.enforce_fcd_ledger_available_balance()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  target_account_id bigint := coalesce(new.account_id, old.account_id);
  target_currency_code text := coalesce(new.currency_code, old.currency_code);
  native_balance numeric(18,2);
  account_has_od boolean;
begin
  select coalesce(sum(native_amount_in - native_amount_out), 0)
    into native_balance
  from public.fcd_ledger_entries
  where account_id = target_account_id
    and currency_code = target_currency_code;

  select coalesce(od_limit, 0) > 0
    into account_has_od
  from public.accounts
  where id = target_account_id;

  if native_balance < 0 and not account_has_od then
    raise exception 'FCD account % currency % has insufficient available balance', target_account_id, target_currency_code;
  end if;

  return null;
end;
$$;

drop trigger if exists enforce_fcd_ledger_available_balance on public.fcd_ledger_entries;
create constraint trigger enforce_fcd_ledger_available_balance
after insert or update or delete on public.fcd_ledger_entries
deferrable initially deferred
for each row execute function public.enforce_fcd_ledger_available_balance();

