create table public.weight_ticket_image_assets (
  id bigint generated by default as identity primary key,
  bucket text not null,
  original_storage_key text not null,
  thumbnail_storage_key text not null,
  file_name text not null,
  mime_type text,
  byte_size bigint,
  thumbnail_status text not null default 'queued',
  attempt_count integer not null default 0,
  next_retry_at timestamptz not null default now(),
  locked_at timestamptz,
  locked_by text,
  source_width integer,
  source_height integer,
  thumbnail_width integer,
  thumbnail_height integer,
  last_error text,
  uploaded_by text,
  attached_ticket_id bigint references public.weight_tickets(id) on delete set null,
  attached_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint weight_ticket_image_assets_status_check
    check (thumbnail_status in ('queued', 'processing', 'ready', 'failed')),
  constraint weight_ticket_image_assets_byte_size_check
    check (byte_size is null or byte_size > 0),
  constraint weight_ticket_image_assets_attempt_count_check
    check (attempt_count >= 0),
  constraint weight_ticket_image_assets_dimensions_check
    check (
      (source_width is null or source_width > 0)
      and (source_height is null or source_height > 0)
      and (thumbnail_width is null or thumbnail_width > 0)
      and (thumbnail_height is null or thumbnail_height > 0)
    ),
  constraint weight_ticket_image_assets_original_key unique (bucket, original_storage_key),
  constraint weight_ticket_image_assets_thumbnail_key unique (bucket, thumbnail_storage_key)
);

create index weight_ticket_image_assets_pending_idx
  on public.weight_ticket_image_assets (thumbnail_status, next_retry_at);
create index weight_ticket_image_assets_owner_idx
  on public.weight_ticket_image_assets (uploaded_by, created_at);
create index weight_ticket_image_assets_ticket_idx
  on public.weight_ticket_image_assets (attached_ticket_id);

alter table public.weight_ticket_image_assets enable row level security;

