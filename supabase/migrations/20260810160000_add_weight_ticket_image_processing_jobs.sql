do $$
declare
  image_record record;
  image_json jsonb;
  image_bucket text;
  image_original_key text;
  image_thumbnail_key text;
  image_file_name text;
  invalid_count integer := 0;
  missing_original_count integer := 0;
begin
  for image_record in
    select ticket_id, raw_value
    from (
      select wt.id as ticket_id, vehicle_image.raw_value
      from public.weight_tickets wt
      cross join lateral unnest(wt.vehicle_image_names) as vehicle_image(raw_value)
      union all
      select wtl.weight_ticket_id as ticket_id, line_image.raw_value
      from public.weight_ticket_lines wtl
      cross join lateral unnest(wtl.image_names) as line_image(raw_value)
    ) existing_images
  loop
    begin
      image_json := image_record.raw_value::jsonb;
    exception when others then
      invalid_count := invalid_count + 1;
      image_json := null;
    end;

    if image_json is not null then
      image_bucket := nullif(trim(image_json ->> 'bucket'), '');
      image_original_key := nullif(trim(image_json ->> 'storageKey'), '');
      image_thumbnail_key := nullif(trim(image_json ->> 'thumbnailStorageKey'), '');
      image_file_name := nullif(trim(image_json ->> 'fileName'), '');

      if image_bucket is null
        or image_original_key is null
        or image_thumbnail_key is null
        or image_file_name is null then
        invalid_count := invalid_count + 1;
      elsif not exists (
        select 1 from storage.objects
        where bucket_id = image_bucket and name = image_original_key
      ) then
        missing_original_count := missing_original_count + 1;
      else
        insert into public.weight_ticket_image_assets (
          bucket,
          original_storage_key,
          thumbnail_storage_key,
          file_name,
          thumbnail_status,
          attached_ticket_id,
          attached_at
        ) values (
          image_bucket,
          image_original_key,
          image_thumbnail_key,
          image_file_name,
          case when exists (
            select 1 from storage.objects
            where bucket_id = image_bucket and name = image_thumbnail_key
          ) then 'ready' else 'queued' end,
          image_record.ticket_id,
          now()
        )
        on conflict (bucket, original_storage_key) do update
        set attached_ticket_id = coalesce(public.weight_ticket_image_assets.attached_ticket_id, excluded.attached_ticket_id),
            attached_at = coalesce(public.weight_ticket_image_assets.attached_at, excluded.attached_at),
            thumbnail_status = case
              when public.weight_ticket_image_assets.thumbnail_status = 'ready'
                and exists (select 1 from storage.objects where bucket_id = public.weight_ticket_image_assets.bucket and name = public.weight_ticket_image_assets.thumbnail_storage_key)
                then 'ready'
              else excluded.thumbnail_status
            end,
            updated_at = now();
      end if;
    end if;
  end loop;

  if invalid_count > 0 or missing_original_count > 0 then
    raise exception 'WTI/WTO image backfill blocked: invalid_or_legacy=% missing_original_object=%; run the image audit and fix source data before promotion', invalid_count, missing_original_count;
  end if;
end $$;
