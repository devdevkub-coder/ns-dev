// Backfill the immutable 1600px JPEG download derivative for existing WTI/WTO images.
// Dry-run is the default. --apply requires --expected-project-ref=<ref>.
// --force regenerates ready derivatives after a quality/config change.
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const sharp = require('sharp')
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { config as loadEnv } from 'dotenv'
import pg from 'pg'
import { createClient } from '@supabase/supabase-js'
import { identifySupabaseProjectRef } from './weight-ticket-image-assets.mjs'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
for (const envPath of [path.resolve(scriptDir, '..', '.env.local'), path.resolve(scriptDir, '..', '.env')]) {
  if (fs.existsSync(envPath)) { loadEnv({ path: envPath, override: false }); break }
}
const APPLY = process.argv.includes('--apply')
const FORCE = process.argv.includes('--force')
const SETTING_KEYS = ['WEIGHT_TICKET_IMAGE_BUCKET', 'WEIGHT_TICKET_DOWNLOAD_MAX_DIMENSION', 'WEIGHT_TICKET_DOWNLOAD_JPEG_QUALITY', 'WEIGHT_TICKET_THUMBNAIL_MAX_SOURCE_PIXELS', 'WEIGHT_TICKET_THUMBNAIL_LOCK_TIMEOUT_SECONDS']

function requiredEnv(name) { const value = process.env[name]?.trim(); if (!value) throw new Error('Missing required env: ' + name); return value }
function expectedProjectRef() { return process.argv.find((value) => value.startsWith('--expected-project-ref='))?.slice('--expected-project-ref='.length).trim() || null }
function integerSetting(settings, key, minimum, maximum) {
  const value = Number(settings.get(key))
  if (!Number.isSafeInteger(value) || value < minimum || value > maximum) throw new Error('Invalid system setting: ' + key)
  return value
}
function assertApplyTarget(projectRef) {
  if (!APPLY) return
  const expected = expectedProjectRef()
  if (!expected || expected !== projectRef) throw new Error(`refusing --apply: expected project ${expected ?? '(missing)'}, resolved project ${projectRef}`)
}
function assertImageStorageKey(value) {
  if (typeof value !== 'string' || value.length === 0 || value.length > 512 || !value.startsWith('attachments/') || value.includes('\\') || value.split('/').some((segment) => !segment || segment === '.' || segment === '..' || !/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(segment))) throw new Error('invalid image storage key')
  return value
}
function errorMessage(error) { return error instanceof Error ? error.message : String(error) }

async function readExistingDownloadDerivative(supabase, bucket, storageKey, expectedBytes, maxDimension) {
  const { data, error } = await supabase.storage.from(bucket).download(storageKey)
  if (error || !data) throw new Error('existing download derivative could not be read: ' + (error?.message ?? 'object not found'))
  const existingBytes = Buffer.from(await data.arrayBuffer())
  if (!existingBytes.equals(expectedBytes)) throw new Error('existing download derivative does not match generated bytes')
  const metadata = await sharp(existingBytes, { failOn: 'error' }).metadata()
  if (metadata.format !== 'jpeg' || !metadata.width || !metadata.height || metadata.width > maxDimension || metadata.height > maxDimension) {
    throw new Error('existing download derivative has invalid JPEG dimensions')
  }
  return { width: metadata.width, height: metadata.height, byteSize: existingBytes.length }
}

async function main() {
  const databaseUrl = requiredEnv('DATABASE_URL')
  const supabaseUrl = requiredEnv('NEXT_PUBLIC_SUPABASE_URL')
  const projectRef = identifySupabaseProjectRef(supabaseUrl, databaseUrl)
  assertApplyTarget(projectRef)
  const { Pool } = pg
  const pool = new Pool({ connectionString: databaseUrl, connectionTimeoutMillis: 5000, max: 1, idleTimeoutMillis: 10000 })
  const supabase = createClient(supabaseUrl, requiredEnv('SUPABASE_SERVICE_ROLE_KEY'), { auth: { autoRefreshToken: false, persistSession: false } })
  try {
    const settingsResult = await pool.query('select key, value from public.system_settings where key = any($1::text[])', [SETTING_KEYS])
    const settings = new Map(settingsResult.rows.map((row) => [row.key, row.value]))
    const bucket = settings.get('WEIGHT_TICKET_IMAGE_BUCKET')?.trim()
    if (!bucket) throw new Error('Missing configured WEIGHT_TICKET_IMAGE_BUCKET')
    const maxDimension = integerSetting(settings, 'WEIGHT_TICKET_DOWNLOAD_MAX_DIMENSION', 320, 2048)
    const quality = integerSetting(settings, 'WEIGHT_TICKET_DOWNLOAD_JPEG_QUALITY', 1, 100)
    const maxSourcePixels = integerSetting(settings, 'WEIGHT_TICKET_THUMBNAIL_MAX_SOURCE_PIXELS', 1_000_000, 300_000_000)
    const lockTimeoutSeconds = integerSetting(settings, 'WEIGHT_TICKET_THUMBNAIL_LOCK_TIMEOUT_SECONDS', 30, 3600)
    const assets = await pool.query(`select id, bucket, original_storage_key, download_storage_key, download_status, download_locked_by
      from public.weight_ticket_image_assets
      ${FORCE ? '' : "where download_status <> 'ready'"}
      order by id asc`)
    const report = { apply: APPLY, force: FORCE, bucket, projectRef, maxDimension, quality, selected: assets.rows.length, generated: 0, skipped: 0, skippedClaim: 0, nonReadyRemaining: 0, errors: [] }
    for (const asset of assets.rows) {
      const lockToken = `download-backfill-${process.pid}-${asset.id}-${Date.now()}`
      let claimed = false
      try {
        if (asset.bucket !== bucket) throw new Error('asset bucket does not match configured image bucket')
        const originalKey = assertImageStorageKey(asset.original_storage_key)
        const downloadKey = assertImageStorageKey(asset.download_storage_key)
        if (originalKey === downloadKey) throw new Error('download derivative key must differ from original key')
        if (!APPLY) { report.skipped += 1; continue }
        const claim = await pool.query(`update public.weight_ticket_image_assets
          set download_status='processing', download_locked_at=now(), download_locked_by=$2,
              download_attempt_count=download_attempt_count+1, download_last_error=null, updated_at=now()
          where id=$1
            and ${FORCE
              ? "((download_status = 'ready' and download_locked_by is null) or (download_status <> 'ready' and (download_locked_by is null or download_locked_at < now() - ($3 * interval '1 second'))))"
              : "download_status <> 'ready' and (download_locked_by is null or download_locked_at < now() - ($3 * interval '1 second'))"}`, [asset.id, lockToken, lockTimeoutSeconds])
        if (claim.rowCount !== 1) { report.skippedClaim += 1; continue }
        claimed = true
        const { data: originalBlob, error: downloadError } = await supabase.storage.from(bucket).download(originalKey)
        if (downloadError || !originalBlob) throw new Error('original download failed: ' + (downloadError?.message ?? 'object not found'))
        const originalBytes = Buffer.from(await originalBlob.arrayBuffer())
        const metadata = await sharp(originalBytes, { failOn: 'error' }).metadata()
        const sourcePixels = (metadata.width ?? 0) * (metadata.height ?? 0)
        if (!metadata.width || !metadata.height || !Number.isSafeInteger(sourcePixels) || sourcePixels > maxSourcePixels) throw new Error('source image exceeds configured pixel limit')
        const image = await sharp(originalBytes, { failOn: 'error' }).rotate().resize({ fit: 'inside', height: maxDimension, kernel: 'lanczos3', withoutEnlargement: true, width: maxDimension }).jpeg({ mozjpeg: true, quality }).toBuffer({ resolveWithObject: true })
        let dimensions = { width: image.info.width, height: image.info.height, byteSize: image.data.length }
        if (FORCE && asset.download_status === 'ready') {
          const { error: removeError } = await supabase.storage.from(bucket).remove([downloadKey])
          if (removeError) throw new Error('existing download derivative removal failed: ' + removeError.message)
        }
        const { error: uploadError } = await supabase.storage.from(bucket).upload(downloadKey, image.data, { cacheControl: '31536000', contentType: 'image/jpeg', upsert: false })
        if (uploadError) {
          if (!/already exists/i.test(uploadError.message)) throw new Error('download derivative upload failed: ' + uploadError.message)
          dimensions = await readExistingDownloadDerivative(supabase, bucket, downloadKey, image.data, maxDimension)
        }
        const markedReady = await pool.query("update public.weight_ticket_image_assets set download_status='ready', download_width=$2, download_height=$3, download_byte_size=$4, download_last_error=null, download_locked_at=null, download_locked_by=null, download_next_retry_at=now(), updated_at=now() where id=$1 and download_locked_by=$5", [asset.id, dimensions.width, dimensions.height, dimensions.byteSize, lockToken])
        if (markedReady.rowCount !== 1) { report.skippedClaim += 1; continue }
        report.generated += 1
      } catch (error) {
        report.errors.push({ id: asset.id, error: errorMessage(error) })
        if (claimed) await pool.query("update public.weight_ticket_image_assets set download_status='failed', download_last_error=$2, download_locked_at=null, download_locked_by=null, updated_at=now() where id=$1 and download_locked_by=$3", [asset.id, errorMessage(error).slice(0, 1000), lockToken]).catch(() => undefined)
      }
    }
    const remaining = await pool.query("select count(*)::int as count from public.weight_ticket_image_assets where download_status <> 'ready'")
    report.nonReadyRemaining = remaining.rows[0]?.count ?? 0
    console.log(JSON.stringify(report, null, 2))
    if (report.errors.length > 0) process.exitCode = 2
  } finally { await pool.end() }
}
main().catch((error) => { console.error(errorMessage(error)); process.exitCode = 1 })
